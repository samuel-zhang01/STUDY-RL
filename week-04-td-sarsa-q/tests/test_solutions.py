def test_ex9_snips_recovers_known_mean():
    rng = np.random.default_rng(0)
    N = 5000
    # target policy uniform over 4 arms, behaviour 50/50 mix on arms 0/1
    behaviour_probs = np.full(N, 0.5)
    target_probs = np.full(N, 0.25)
    # reward generated by behaviour: arm gives mean=2 if arm==0 else 0
    arms = rng.integers(0, 2, size=N)
    rewards = (arms == 0).astype(float) * 2.0
    # target policy uses each arm with prob 0.25, so target mean reward over arms 0/1 is
    # but since only arms 0/1 ever appear in our log, SNIPS estimate uses only those.
    est = S.exercise_9_snips(rewards, behaviour_probs, target_probs)
    # half the logged data has arm==0 (reward 2), half has arm==1 (reward 0).
    # IS weights are all 0.5 so SNIPS is just mean rewards ~= 1.0
    assert 0.7 < est < 1.3
