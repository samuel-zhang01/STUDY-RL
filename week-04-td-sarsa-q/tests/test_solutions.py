def test_ex1_td0_terminal_handling():
    V = np.zeros(4)
    traj = [(0, 1.0, 1), (1, 2.0, -1)]
    V_new = S.exercise_1_td0(traj, V, alpha=1.0, gamma=1.0)
    # First update: V[0] += 1*(1 + 0 - 0) = 1
    # Second update: V[1] += 1*(2 + 0 - 0) = 2 (terminal: no bootstrap)
    assert V_new[0] == 1.0
    assert V_new[1] == 2.0


def test_ex2_nstep_return():
    # rewards = [1,2,3], V_terminal = 10, gamma=1, n=2 -> 1 + 2 + 1*10 = 13
    assert S.exercise_2_nstep_return([1, 2, 3], 10.0, 1.0, 2) == 13.0
    # n=3 (all rewards consumed but trajectory longer? len(rewards)=3 == n -> bootstrap)
    assert S.exercise_2_nstep_return([1, 2, 3], 10.0, 1.0, 3) == 1 + 2 + 3 + 10
    # n > len(rewards): no bootstrap
    assert S.exercise_2_nstep_return([1, 2], 10.0, 1.0, 5) == 3.0


def test_ex3_sarsa_step():
    Q = np.zeros((3, 2))
    Qn = S.exercise_3_sarsa_step(Q, 0, 1, 1.0, 1, 0, False, 0.5, 1.0)
    assert Qn[0, 1] == 0.5  # 0 + 0.5*(1+0-0)
    Qn = S.exercise_3_sarsa_step(Q, 0, 1, 1.0, 1, 0, True, 0.5, 1.0)
    assert Qn[0, 1] == 0.5


def test_ex4_qlearn_step():
    Q = np.array([[0.0, 0.0], [3.0, 5.0]])
    Qn = S.exercise_4_qlearn_step(Q, 0, 1, 1.0, 1, False, 0.5, 1.0)
    # target = 1 + 1*5 = 6 ; Q[0,1] += 0.5*(6-0) = 3
    assert Qn[0, 1] == 3.0


def test_ex5_expected_sarsa_target():
    Q_sp = np.array([1.0, 5.0, 2.0])
    # eps = 0 -> just max = 5
    assert S.exercise_5_expected_sarsa_target(Q_sp, 0.0) == 5.0
    # eps = 1 -> uniform = mean = 8/3
    assert abs(S.exercise_5_expected_sarsa_target(Q_sp, 1.0) - (8.0 / 3.0)) < 1e-9


def test_ex6_double_q_step():
    Q1 = np.zeros((2, 2)); Q2 = np.array([[0.0, 0.0], [3.0, 7.0]])
    # update_first=True: a_star = argmax Q1[1] = 0 ; target = 0 + 1*Q2[1,0] = 3
    Q1n, Q2n = S.exercise_6_double_q_step(Q1, Q2, 0, 1, 0.0, 1, False, 1.0, 1.0, True)
    assert Q1n[0, 1] == 3.0
    assert (Q2n == Q2).all()


def test_ex7_td_vs_mc_variance():
    rng = np.random.default_rng(0)
    eps_data = [list(rng.normal(0, 1, size=10)) for _ in range(500)]
    v_td, v_mc = S.exercise_7_td_error_var(eps_data, V_true=0.0, gamma=1.0)
    # var_TD should be ~1 (var of N(0,1)), var_MC should be ~10
    assert v_td < v_mc
    assert 0.5 < v_td < 1.5
    assert 7.0 < v_mc < 13.0


